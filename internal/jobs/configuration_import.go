// Import failures never expose private paths or SQLite details.
var (
	ErrImportConflict = errors.New("IMPORT_CONFLICT")
	ErrImportUnmapped = errors.New("IMPORT_UNMAPPED")
)

// configurationDigest hashes one canonical typed value without retaining the uploaded bundle in replay storage.
func configurationDigest(v any) string {
	raw, _ := json.Marshal(v)
	sum := sha256.Sum256(raw)
	return hex.EncodeToString(sum[:])
}

// ValidateConfigurationImport preserves explicit selections and refuses ambiguous duplicate mappings.
func ValidateConfigurationImport(in contracts.ConfigurationImportRequest, apply bool) error {
	if in.ContractVersion != 1 || !ValidConfigurationBundle(in.Bundle) || (in.Expected != nil) != apply || in.Selection.ProfileIDs == nil || len(in.Selection.ProfileIDs) > 200 || in.Mappings == nil || len(in.Mappings) > contracts.ConfigurationMappingLimit {
		return ErrInvalid
	}
	known := map[string]bool{}
	targets := map[string]bool{}
	for _, p := range in.Bundle.Profiles {
		known[p.SourceProfileID] = true
		for _, id := range p.Configuration.Scope.TargetIDs {
			targets[id] = true
		}
	}
	seen := map[string]bool{}
	for _, id := range in.Selection.ProfileIDs {
		if !known[id] || seen[id] {
			return ErrInvalid
		}
		seen[id] = true
	}
	seen = map[string]bool{}
	for _, m := range in.Mappings {
		if !targets[m.SourceTargetID] || seen[m.SourceTargetID] || m.TargetID != nil && !security.ValidID(*m.TargetID) {
			return ErrInvalid
		}
		seen[m.SourceTargetID] = true
	}
	if apply && !validConfigurationExpectation(*in.Expected) {
		return ErrInvalid
	}
	raw, e := json.Marshal(in)
	if e != nil || len(raw) > contracts.ConfigurationImportLimit {
		return ErrConfigurationTooLarge
	}
	return nil
}

// DecodeConfigurationImport additionally requires every exported field, including explicit null and false values.
func DecodeConfigurationImport(raw []byte, in *contracts.ConfigurationImportRequest, apply bool) error {
	if len(raw) > contracts.ConfigurationImportLimit {
		return ErrConfigurationTooLarge
	}
	if security.DecodeJSON(bytes.NewReader(raw), contracts.ConfigurationImportLimit, in) != nil {
		return ErrInvalid
	}
	var fields map[string]json.RawMessage
	if json.Unmarshal(raw, &fields) != nil {
		return ErrInvalid
	}
	if len(fields["bundle"]) > contracts.ConfigurationBundleLimit {
		return ErrConfigurationTooLarge
	}
	canonical, e := json.Marshal(in)
	if e != nil {
		return ErrInvalid
	}
	var a, b any
	x, y := json.NewDecoder(bytes.NewReader(raw)), json.NewDecoder(bytes.NewReader(canonical))
	x.UseNumber()
	y.UseNumber()
	if x.Decode(&a) != nil || y.Decode(&b) != nil || !reflect.DeepEqual(a, b) {
		return ErrInvalid
	}
	return ValidateConfigurationImport(*in, apply)
}

// validConfigurationExpectation accepts only bounded values generated by the preview contract.
func validConfigurationExpectation(e contracts.ConfigurationExpectation) bool {
	_, err := hex.DecodeString(e.CatalogDigest)
	return err == nil && len(e.CatalogDigest) == 64 && e.PreferenceRevision >= 0 && e.PreferenceRevision <= MaxPreferenceRevision && e.TemplateRevision >= 0 && e.TemplateRevision <= MaxPreferenceRevision && e.MappingRevision >= 1 && e.MappingRevision <= 9007199254740991 && e.ProfileCount >= 0 && e.ProfileCount <= 200 && (RetentionRequest{ContractVersion: 1, CompleteCount: e.RetentionCompleteCount}).Validate() == nil
}

// importSelectionDigest binds exact ordered selection and mappings, independently of the bundle.
func importSelectionDigest(in contracts.ConfigurationImportRequest) string {
	return configurationDigest(struct {
		Selection contracts.ConfigurationSelection       `json:"selection"`
		Mappings  []contracts.ConfigurationTargetMapping `json:"mappings"`
	}{in.Selection, in.Mappings})
}

// importCatalogDigest excludes volatile capacity counters while binding actual source identity, state and paths privately.
func importCatalogDigest(s profileSources) string {
	rows := []string{s.Mode, s.BootID}
	for _, v := range s.Volumes {
		rows = append(rows, configurationDigest([]any{v.ID, v.MountPath, v.IdentityEvidence, v.State, v.Filesystem}))
	}
	for _, v := range s.Shares {
		rows = append(rows, configurationDigest([]any{v.ID, v.VolumeID, v.PhysicalPath, v.IdentityEvidence, v.State, v.Readable, v.Locked, v.FileStationPath, v.Encrypted}))
	}
	sort.Strings(rows)
	return configurationDigest(rows)
}

// importReadState reads all before-values in the caller's single consistent transaction.
func importReadState(ctx context.Context, tx *sql.Tx, principal string) (contracts.ConfigurationCurrentSettings, contracts.ConfigurationExpectation, error) {
	var c contracts.ConfigurationCurrentSettings
	var ex contracts.ConfigurationExpectation
	p, e := readPreferences(ctx, tx, principal)
	if e != nil {
		return c, ex, e
	}
	t, e := readExclusionTemplate(ctx, tx)
	if e != nil {
		return c, ex, e
	}
	m, e := readFileTypeMapping(ctx, tx)
	if e != nil {
		return c, ex, e
	}
	if e = tx.QueryRowContext(ctx, `SELECT complete_count FROM retention_settings WHERE singleton=1`).Scan(&c.RetentionCompleteCount); e != nil {
		return c, ex, e
	}
	if e = tx.QueryRowContext(ctx, `SELECT count(*) FROM profiles`).Scan(&ex.ProfileCount); e != nil {
		return c, ex, e
	}
	c.Appearance = contracts.PreferenceAppearance{Language: p.Language, Theme: p.Theme, Map: p.Map, Locale: p.Locale, TimeZone: p.TimeZone}
	c.Display = p.Display
	c.PreferredProfileRef = p.PreferredProfileID
	c.ExclusionTemplate = contracts.ConfigurationTemplate{Rules: t.Rules}
	c.FileTypeMapping = m
	ex.PreferenceRevision = p.Revision
	ex.TemplateRevision = t.Revision
	ex.MappingRevision = m.Revision
	ex.RetentionCompleteCount = c.RetentionCompleteCount
	return c, ex, nil
}

// importPreview computes explicit missing mappings and never infers names or reuses source profile IDs.
func importPreview(in contracts.ConfigurationImportRequest, s profileSources, current contracts.ConfigurationCurrentSettings, ex contracts.ConfigurationExpectation) (contracts.ConfigurationImportPreview, map[string]contracts.Profile, error) {
	out := contracts.ConfigurationImportPreview{BundleDigest: configurationDigest(in.Bundle), SelectionDigest: importSelectionDigest(in), Expected: ex, Profiles: []contracts.ConfigurationProfilePreview{}, UnassignedTargetIDs: []string{}, Settings: contracts.ConfigurationSettingsPreview{Current: current, Selected: in.Selection.Settings}, TasksRequireReview: true, Issues: []string{}}
	out.Expected.CatalogDigest = importCatalogDigest(s)
	selected := map[string]bool{}
	for _, id := range in.Selection.ProfileIDs {
		selected[id] = true
	}
	mappings := map[string]*string{}
	for _, m := range in.Mappings {
		mappings[m.SourceTargetID] = m.TargetID
	}
	available := map[string]bool{}
	for _, v := range s.Volumes {
		available[v.ID] = true
	}
	for _, v := range s.Shares {
		available[v.ID] = true
	}
	missing := map[string]bool{}
	prepared := map[string]contracts.Profile{}
	allReady := true
	for _, source := range in.Bundle.Profiles {
		row := contracts.ConfigurationProfilePreview{SourceProfileID: source.SourceProfileID, Name: source.Configuration.Name, Selected: selected[source.SourceProfileID], Ready: true, Issues: []string{}}
		c := source.Configuration
		p := contracts.Profile{ID: source.SourceProfileID, Revision: 1, Name: c.Name, Scope: contracts.Scope{Kind: c.Scope.Kind, TargetIDs: []string{}, RelativePath: c.Scope.RelativePath}, Active: false, Exclusions: c.Exclusions, ResourceMode: c.ResourceMode, Limits: c.Limits, FreshnessSeconds: c.FreshnessSeconds}
		issue := func(code string) {
			row.Ready = false
			for _, old := range row.Issues {
				if old == code {
					return
				}
			}
			row.Issues = append(row.Issues, code)
		}
		for _, id := range c.Scope.TargetIDs {
			target := mappings[id]
			if target == nil {
				issue("MISSING_MAPPING")
				if row.Selected {
					missing[id] = true
				}
				continue
			}
			if !available[*target] {
				issue("TARGET_UNAVAILABLE")
				if row.Selected {
					missing[id] = true
				}
				continue
			}
			p.Scope.TargetIDs = append(p.Scope.TargetIDs, *target)
		}
		if _, e := resources.Resolve(p.ResourceMode, p.Limits); e != nil {
			issue("RESOURCE_UNSUPPORTED")
		}
		if row.Ready {
			n, e := normalizeSources(p.Scope, s)
			if e != nil {
				issue("SCOPE_INVALID")
			} else {
				for _, root := range n.Roots {
					if root.State != "reachable" {
						issue("TARGET_UNAVAILABLE")
					}
				}
			}
			seenTargets := map[string]bool{}
			for _, target := range p.Scope.TargetIDs {
				if seenTargets[target] {
					issue("SCOPE_INVALID")
				}
				seenTargets[target] = true
			}
		}
		if row.Selected && ex.ProfileCount+len(selected) > 200 {
			issue("PROFILE_LIMIT")
		}
		if row.Selected {
			allReady = allReady && row.Ready
			prepared[source.SourceProfileID] = p
		}
		out.Profiles = append(out.Profiles, row)
	}
	if len(missing) > contracts.ConfigurationMappingLimit {
		return out, nil, ErrInvalid
	}
	for id := range missing {
		out.UnassignedTargetIDs = append(out.UnassignedTargetIDs, id)
	}
	sort.Strings(out.UnassignedTargetIDs)
	if in.Selection.Settings.PreferredProfile && in.Bundle.Personal.PreferredProfileRef != nil && !selected[*in.Bundle.Personal.PreferredProfileRef] {
		allReady = false
		out.Issues = append(out.Issues, "PREFERRED_PROFILE_UNMAPPED")
		for i := range out.Profiles {
			if out.Profiles[i].SourceProfileID == *in.Bundle.Personal.PreferredProfileRef {
				out.Profiles[i].Issues = append(out.Profiles[i].Issues, "PREFERRED_PROFILE_UNMAPPED")
			}
		}
	}
	out.CanApply = allReady && (len(selected) > 0 || in.Selection.Settings != (contracts.ConfigurationSettingsSelection{}))
	return out, prepared, nil
}

// PreviewConfigurationImport performs no writes and does not reserve future profile identities.
func (m *Manager) PreviewConfigurationImport(parent context.Context, in contracts.ConfigurationImportRequest, principal string) (contracts.ConfigurationImportPreview, error) {
	var zero contracts.ConfigurationImportPreview
	if !validPrincipal(principal) || ValidateConfigurationImport(in, false) != nil {
		return zero, ErrInvalid
	}
	ctx, cancel := m.observationContext(parent)
	defer cancel()
	s, e := m.catalog(ctx, profileSources{Version: 1, Mode: "native_inventory"})
	if e != nil || s.Mode != "native_inventory" {
		return zero, ErrUnavailable
	}
	out, e := retryControlRead(ctx, func() (contracts.ConfigurationImportPreview, error) {
		tx, e := m.readDB.BeginTx(ctx, &sql.TxOptions{ReadOnly: true})
		if e != nil {
			return zero, e
		}
		defer tx.Rollback()
		current, expected, e := importReadState(ctx, tx, principal)
		if e != nil {
			return zero, e
		}
		out, _, e := importPreview(in, s, current, expected)
		if e != nil {
			return zero, e
		}
		if e = tx.Commit(); e != nil {
			return zero, e
		}
		return out, nil
	})
	return out, observationError(e)
}

// ValidConfigurationImportPreview qualifies bounded transport receipts against the submitted selection.
func ValidConfigurationImportPreview(out contracts.ConfigurationImportPreview, in contracts.ConfigurationImportRequest) bool {
	if out.BundleDigest != configurationDigest(in.Bundle) || out.SelectionDigest != importSelectionDigest(in) || !validConfigurationExpectation(out.Expected) || !out.TasksRequireReview || out.Profiles == nil || len(out.Profiles) != len(in.Bundle.Profiles) || out.UnassignedTargetIDs == nil || len(out.UnassignedTargetIDs) > contracts.ConfigurationMappingLimit || out.Issues == nil || len(out.Issues) > 8 || out.Settings.Selected != in.Selection.Settings {
		return false
	}
	validIssue := func(s string) bool {
		switch s {
		case "MISSING_MAPPING", "TARGET_UNAVAILABLE", "SCOPE_INVALID", "RESOURCE_UNSUPPORTED", "PROFILE_LIMIT", "PREFERRED_PROFILE_UNMAPPED":
			return true
		}
		return false
	}
	selected := map[string]bool{}
	for _, id := range in.Selection.ProfileIDs {
		selected[id] = true
	}
	for i, p := range out.Profiles {
		if p.SourceProfileID != in.Bundle.Profiles[i].SourceProfileID || p.Name != in.Bundle.Profiles[i].Configuration.Name || p.Selected != selected[p.SourceProfileID] || p.Issues == nil || len(p.Issues) > 8 {
			return false
		}
		for _, s := range p.Issues {
			if !validIssue(s) {
				return false
			}
		}
		if out.CanApply && p.Selected && !p.Ready {
			return false
		}
	}
	for _, s := range out.Issues {
		if !validIssue(s) {
			return false
		}
	}
	if out.CanApply && len(out.Issues) > 0 {
		return false
	}
	seen := map[string]bool{}
	for _, id := range out.UnassignedTargetIDs {
		if !security.ValidID(id) || seen[id] {
			return false
		}
		seen[id] = true
	}
	if out.CanApply && len(seen) > 0 {
		return false
	}
	c := out.Settings.Current
	b := contracts.ConfigurationBundle{FormatVersion: 1, ExportedAt: "2026-01-01T00:00:00Z", Profiles: []contracts.ConfigurationProfile{}, Global: contracts.ConfigurationGlobal{ExclusionTemplate: c.ExclusionTemplate, RetentionCompleteCount: c.RetentionCompleteCount, FileTypeMapping: c.FileTypeMapping}, Personal: contracts.ConfigurationPersonal{Appearance: c.Appearance, Display: c.Display, PreferredProfileRef: c.PreferredProfileRef}}
	if !ValidConfigurationBundle(b) || c.FileTypeMapping.Revision != out.Expected.MappingRevision || c.RetentionCompleteCount != out.Expected.RetentionCompleteCount {
		return false
	}
	raw, e := json.Marshal(out)
	return e == nil && len(raw) <= contracts.ConfigurationPreviewLimit-4096
}
