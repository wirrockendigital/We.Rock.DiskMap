#!/bin/sh
set -eu
# Require the exact recorded target; never infer an architecture from the builder.
cd "$(dirname "$0")/.."
python3 scripts/native_targets.py "${1:-}"
: "${GO:=go}"
if [ "$("$GO" env GOVERSION)" != go1.27.2 ]; then
  echo 'Go 1.27.2 is required.' >&2
  exit 2
fi
if [ "$(node --version)" != v24.2.0 ] || [ "$(npm --version)" != 11.3.0 ]; then
  echo 'Node 24.2.0 and npm 11.3.0 are required.' >&2
  exit 2
fi
# Every new native build consumes the next patch identity under the project release contract.
python3 scripts/bump-build-version.py
# UI assets are local and the only application binaries target the recorded x86-64 DSM target.
# Remove only fixed generated trees so stale outputs cannot enter a successful build.
python3 - <<'PY_CLEAN'
from pathlib import Path
import shutil
for name in ('dist/bin', 'dist/ui', 'web/dist'):
    path = Path(name)
    if path.is_symlink():
        raise SystemExit('Refusing symlinked build output')
    if path.exists():
        shutil.rmtree(path)
Path('dist/build-output.json').unlink(missing_ok=True)
PY_CLEAN
mkdir -p dist/bin dist/ui
python3 scripts/source_manifest.py > dist/source-before.json
# Pass only the fresh source identity; the generated manifest is never itself a source input.
DISKMAP_BUILD_SOURCE_ID="$(python3 -c 'import json; print(json.load(open("dist/source-before.json"))["sourceId"])')" GO="$GO" npm --prefix web run build
cp -R web/dist/. dist/ui/
export GOOS=linux GOARCH=amd64 GOAMD64=v1 CGO_ENABLED=0 GOTOOLCHAIN=local
"$GO" build -buildvcs=false -trimpath -ldflags='-s -w -buildid=' -o dist/bin/diskmapd ./cmd/diskmapd
"$GO" build -buildvcs=false -trimpath -ldflags='-s -w -buildid=' -o dist/bin/diskmapctl ./cmd/diskmapctl
"$GO" build -buildvcs=false -trimpath -ldflags='-s -w -buildid=' -o dist/ui/api.cgi ./cmd/diskmap-cgi
# Refuse a candidate when shared sources changed while compilation was running.
python3 scripts/source_manifest.py > dist/source-after.json
cmp dist/source-before.json dist/source-after.json

# Bind the exact generated bytes to the unchanged source only after every compiler succeeds.
python3 scripts/package-spk.py --seal "$1"
